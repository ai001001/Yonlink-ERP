'use strict';
/**
 * 构建 GitHub Pages 浏览器演示版：把后台代码与前端打包为纯静态站点（输出 dist/）
 * Build the GitHub Pages browser demo: bundle server code and front-end into a static site (dist/).
 * 用法 / usage: node scripts/build-pages.js
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const SERVER_FILES = ['security.js', 'http.js', 'core.js', 'db.js', 'entities.js', 'xlsx.js', 'xlsx-read.js', 'migrate.js', 'mail.js', 'rates.js',
  'routes/base.js', 'routes/sales.js', 'routes/orders.js', 'routes/finance.js', 'routes/reports.js', 'routes/integrations.js', 'routes/migrate.js', 'routes/handover.js', 'routes/shipping.js', 'routes/ledger.js'];

/**
 * 递归复制目录 / Copy a directory recursively.
 * @param {string} src
 * @param {string} dst
 */
function copyDir(src, dst) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, e.name);
    const d = path.join(dst, e.name);
    if (e.isDirectory()) copyDir(s, d); else fs.copyFileSync(s, d);
  }
}

fs.rmSync(DIST, { recursive: true, force: true });
copyDir(path.join(ROOT, 'public'), DIST);
copyDir(path.join(ROOT, 'pages', 'vendor'), path.join(DIST, 'vendor'));

// 打包后台模块 / bundle server modules
const defs = SERVER_FILES.map((f) => {
  const src = fs.readFileSync(path.join(ROOT, 'server', f), 'utf8');
  return `  ${JSON.stringify('server/' + f)}: function (module, exports, require) {\n${src}\n  },`;
}).join('\n');
const backend = [
  '/* 自动生成，请勿手改 / Generated by scripts/build-pages.js — do not edit */',
  fs.readFileSync(path.join(ROOT, 'pages', 'shims.js'), 'utf8'),
  `const MODULE_DEFS = {\n${defs}\n};`,
  fs.readFileSync(path.join(ROOT, 'pages', 'runtime.js'), 'utf8'),
].join('\n');
fs.writeFileSync(path.join(DIST, 'js', 'backend.js'), backend);

// 在前端脚本之前注入 sql.js 与后台运行时 / inject sql.js and backend runtime before front-end scripts
const indexFile = path.join(DIST, 'index.html');
const html = fs.readFileSync(indexFile, 'utf8');
const marker = '<script src="js/core.js"></script>';
if (!html.includes(marker)) throw new Error('index.html 中找不到 js/core.js 引用');
fs.writeFileSync(indexFile, html
  .replace(marker, `<script src="vendor/sql-wasm.js"></script>\n  <script src="js/backend.js"></script>\n  ${marker}`)
  .replace('<title>陶瓷工艺品外贸ERP</title>', '<title>陶瓷工艺品外贸ERP（在线演示）</title>')
  // 演示版需要运行 WebAssembly 版 SQLite 并从浏览器获取汇率 / the demo runs WebAssembly SQLite and fetches rates from the browser
  .replace("script-src 'self';", "script-src 'self' 'wasm-unsafe-eval';")
  .replace("connect-src 'self';", "connect-src 'self' https://open.er-api.com https://api.frankfurter.app;"));
fs.writeFileSync(path.join(DIST, '.nojekyll'), '');

// 生成半年模拟业务数据（--no-data 跳过）/ generate six months of simulated data (skip with --no-data)
if (process.argv.includes('--no-data')) {
  console.log('已生成 GitHub Pages 演示版（无模拟数据）/ built without data:', DIST);
} else {
  const os = require('node:os');
  const { seedDemo } = require('./seed-demo');
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'erp-demo-'));
  const file = path.join(tmp, 'demo.db');
  process.env.ERP_SECRET_KEY = process.env.ERP_SECRET_KEY || 'pages-demo-build';
  seedDemo({ dbFile: file, log: console.log }).then((r) => {
    r.app.db.close();
    fs.copyFileSync(file, path.join(DIST, 'demo.db'));
    fs.rmSync(tmp, { recursive: true, force: true });
    console.log('模拟数据 / data:', JSON.stringify(r.stats));
    console.log('已生成 GitHub Pages 演示版 / built:', DIST);
  }).catch((e) => { console.error(e); process.exit(1); });
}
